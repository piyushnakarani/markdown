/**
 * Curated English keyword banks for tool / landing pages (~50 each).
 *
 * Strategy (keyword-research + site SEO):
 * 1. Position 0 = primary money / page-owning intent (no cross-tool cannibalization).
 * 2. Clusters: head → free/online → no-signup/privacy → format features →
 *    Mermaid/math → use-case long tails → brand.
 * 3. Used in <meta name="keywords"> via withToolBrandKeywords (cap 50).
 * 4. Google ignores meta keywords for ranking; lists stay unique & non-spammy
 *    for Bing/Yandex, internal linking hints, and content briefs.
 */

function unique(keywords: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of keywords) {
    const k = raw.trim().toLowerCase();
    if (!k || seen.has(k)) continue;
    seen.add(k);
    out.push(k);
  }
  return out;
}

