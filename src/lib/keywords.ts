export type LocaleKeywordMap = Record<Locale, readonly string[]>;

/**
 * SEO keyword strategy (tool pages)
 * ---------------------------------------------------------------
 * 1. One primary intent per URL (no cannibalization across tools).
 * 2. EN banks (~50) lead with primary + free/online + privacy + features.
 * 3. Locale maps add translated long-tails; merged via keywordsForLocale.
 * 4. Meta keyword cap is 50 (withToolBrandKeywords in this file).
 *
 * THIS FILE IS THE SINGLE SOURCE OF TRUTH for all SEO keywords
 * (tools, landings, brand, defaults, blogs).
 */
export function keywordsForLocale(
  locale: string,
  localeMap: LocaleKeywordMap | Partial<LocaleKeywordMap>,
  shared: readonly string[] = [],
): string[] {
  const resolved =
    (localeMap as Partial<LocaleKeywordMap>)[locale as Locale] ??
    (localeMap as Partial<LocaleKeywordMap>).en ??
    [];
  // Non-English: put native long-tails first so they survive META_KEYWORDS_MAX.
  if (locale !== 'en' && resolved.length > 0) {
    return [...new Set([...resolved, ...shared])];
  }
  return [...new Set([...shared, ...resolved])];
}

function assertAllLocales<T extends Partial<Record<Locale, unknown>>>(
  map: T,
  label: string,
): asserts map is T & Record<Locale, unknown> {
  const missing = locales.filter((l) => !(l in map) || map[l] == null);
  if (missing.length > 0 && process.env.NODE_ENV !== 'production') {
    console.warn(`[keywords] ${label} missing locales: ${missing.join(', ')}`);
  }
}

